import { mkdir } from 'node:fs/promises';
import { join } from 'node:path';

/**
 * Run directory layout (documented in `packages/orchestration/README.md` and task 5.3):
 *
 *   runs/<runId>/
 *     events.jsonl     append-only canonical FactoryEvent log (one JSON object per line)
 *     patch.diff       `git diff` of the sandbox workspace at run end
 *     artifacts/       copied artifacts (logs, screenshots, files)
 *
 * The directory is retained after a run reaches a terminal state (spec: cleanup keeps the
 * run directory, removes the sandbox).
 */
export function runDir(runsRoot: string, runId: string): string {
  return join(runsRoot, sanitizeRunId(runId));
}

export function eventsPath(runsRoot: string, runId: string): string {
  return join(runDir(runsRoot, runId), 'events.jsonl');
}

export function artifactsDir(runsRoot: string, runId: string): string {
  return join(runDir(runsRoot, runId), 'artifacts');
}

export function patchPath(runsRoot: string, runId: string): string {
  return join(runDir(runsRoot, runId), 'patch.diff');
}

export async function ensureRunDir(runsRoot: string, runId: string): Promise<string> {
  const dir = runDir(runsRoot, runId);
  await mkdir(dir, { recursive: true });
  await mkdir(artifactsDir(runsRoot, runId), { recursive: true });
  return dir;
}

/** Run ids are generated by the API, but never trust them as a path component. */
export function sanitizeRunId(runId: string): string {
  const sanitized = runId.replace(/[^A-Za-z0-9_.-]+/g, '-').replace(/^[.-]+/, '');
  if (sanitized === '') throw new Error(`invalid runId "${runId}"`);
  return sanitized.slice(0, 128);
}
